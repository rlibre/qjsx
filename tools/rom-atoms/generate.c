// Writes engine/qjsx/core/rom-atoms.h and rom-atoms.c: the names (atoms) that
// a new QuickJS context makes, laid out as atom strings in read-only memory.
// Built with the engine of the devices (no compiler) and QJSX_ROM_ATOMS=0 by
// generate.sh, which runs it.
// Usage: generate <output folder>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "quickjs-internal.h"

#define MAX_ATOMS 4096           // more than the names of a new context

// ### Names ###################################################################

// One name of the table.
typedef struct Name {
    uint32_t       index;        // atom index in the generated table
    int            isSymbol;     // a predefined symbol: made in the heap at start
    uint32_t       hash;         // JSString.hash (hash of the text, 30 bits)
    uint32_t       length;       // characters, without the final 0
    const uint8_t *text;         // 8 bit characters (in the runtime's atom)
} Name;

static Name names[MAX_ATOMS];    // by generated index; 0 unused (JS_ATOM_NULL)
static int nameCount;            // generated indexes 0 .. nameCount - 1

/**
 * Fills 'names' from the atoms of a runtime with a full context: the
 * predefined atoms keep their index (JS_ATOM_xxx constants), the others follow
 * in their order of creation, without the free entries. Exits on a name that
 * cannot be in read-only memory (a wide string, a symbol not predefined).
 */
static void collectNames(JSRuntime *rt) {
    // the predefined atoms keep the first indexes
    nameCount = JS_ATOM_END;

    for (int i = 1; i < rt->atom_size; i++) {
        JSAtomStruct *p = rt->atom_array[i];
        if (atom_is_free(p)) {
            continue;
        }

        // where it goes: its own index if predefined, else the next one
        bool predefined = i < JS_ATOM_END;
        uint32_t index = (uint32_t)i;
        if (!predefined) {
            index = (uint32_t)nameCount;
            nameCount++;
        }

        if (nameCount > MAX_ATOMS) {
            fprintf(stderr, "generate: more than %d names\n", MAX_ATOMS);
            exit(1);
        }

        // a string atom of 8 bit characters, or a predefined symbol
        Name *name = &names[index];
        name->index = index;
        name->isSymbol = p->atom_type != JS_ATOM_TYPE_STRING;
        bool symbolNotPredefined = name->isSymbol && i >= JS_ATOM_END;
        if (symbolNotPredefined) {
            fprintf(stderr, "generate: atom %d is a symbol that is not predefined\n", i);
            exit(1);
        }

        if (p->is_wide_char) {
            fprintf(stderr, "generate: atom %d is a wide string\n", i);
            exit(1);
        }

        // its hash, its length, its text (kept in the runtime's atom)
        name->hash = p->hash;
        name->length = p->len;
        name->text = p->u.str8;
    }
}

/**
 * What identifies the table: a hash (FNV-1a, 32 bits) of the number of
 * names and, for each index in order, of its kind and of its text. A
 * package made with another table is refused (JS_SetPackageAtoms).
 */
static uint32_t fingerprintOfNames(void) {
    // FNV-1a: offset basis 2166136261, prime 16777619
    uint32_t hash = 2166136261u;

    for (int i = 0; i < nameCount; i++) {
        // the index (its low byte), the kind, the characters
        hash = (hash ^ (uint8_t)i) * 16777619u;
        hash = (hash ^ (uint8_t)names[i].isSymbol) * 16777619u;

        for (uint32_t k = 0; k < names[i].length; k++) {
            hash = (hash ^ names[i].text[k]) * 16777619u;
        }
    }

    return hash;
}

// ### Output ##################################################################

static const char *FILE_HEADER =
    "/*          _\n"
    " *  __ _   (_)  ___ __ __    qjsx - JavaScript for devices\n"
    " * / _` |  | | (_-< \\ \\ /    Author: Etienne Cochard + Opus 5.5\n"
    " * \\__, | _/ | /__/ /_\\_\\    Copyright (c) 2026 R-LIBRE INGENIERIE\n"
    " *    |_| |__/               SPDX-License-Identifier: MIT (see LICENSE)\n"
    " */\n"
    "\n"
    "/* GENERATED by tools/rom-atoms/generate.sh: do not edit. Run it again after\n"
    "   a change of the engine's built-in objects (names added or removed). */\n";

/**
 * Writes 'text' as a C string literal (printable ASCII as is, the rest in
 * octal escapes).
 */
static void writeLiteral(FILE *out, const uint8_t *text, uint32_t length) {
    fputc('"', out);

    for (uint32_t i = 0; i < length; i++) {
        // a quote or a backslash escaped; printable ASCII as is ('?' escaped:
        // no trigraph); the rest in octal
        int c = text[i];
        bool needsBackslash = c == '"' || c == '\\';
        bool printable = c >= 0x20 && c < 0x7f && c != '?';
        if (needsBackslash) {
            fprintf(out, "\\%c", c);
        } else if (printable) {
            fputc(c, out);
        } else {
            fprintf(out, "\\%03o", c);
        }
    }

    fputc('"', out);
}

/**
 * Opens 'folder/file' for writing; exits on failure.
 */
static FILE *openOutput(const char *folder, const char *file) {
    char path[1024];
    snprintf(path, sizeof(path), "%s/%s", folder, file);
    FILE *out = fopen(path, "wb");
    if (out == NULL) {
        fprintf(stderr, "generate: cannot write %s\n", path);
        exit(1);
    }

    return out;
}

/**
 * Writes rom-atoms.h: the number of names, the size of the hash table, the
 * type of the block of names (one member per string, laid out as an atom
 * allocated by QuickJS: block header, JSString, characters) and the tables.
 */
static void writeHeader(const char *folder, uint32_t hashSize) {
    // the file, its header and guard, the constants
    FILE *out = openOutput(folder, "rom-atoms.h");
    fputs(FILE_HEADER, out);
    fputs("\n#ifndef QJSX_ROM_ATOMS_H\n#define QJSX_ROM_ATOMS_H\n\n", out);
    fprintf(out, "/* atom indexes 0 .. QJSX_ROM_ATOM_COUNT - 1 are made at start */\n");
    fprintf(out, "#define QJSX_ROM_ATOM_COUNT %d\n", nameCount);
    fprintf(out, "/* identifies these names and their indexes: a package is made for one\n"
                 "   table of names (JS_GetAtomsFingerprint) */\n");
    fprintf(out, "#define QJSX_ROM_ATOM_FINGERPRINT 0x%08xu\n", fingerprintOfNames());
    fprintf(out, "/* slots of qjsx_rom_atom_hash (a power of two) */\n");
    fprintf(out, "#define QJSX_ROM_ATOM_HASH_SIZE %u\n\n", hashSize);

    // the block: one member per string name
    fputs("/* the names, each as QuickJS allocates an atom string */\n", out);
    fputs("typedef struct QJSXRomAtoms {\n", out);

    for (int i = 1; i < nameCount; i++) {
        if (names[i].isSymbol) {
            continue;
        }

        fprintf(out, "    struct { JSMallocBlockHeader header; JSString string; uint8_t text[%u]; } a%d;\n",
            names[i].length + 1, i);
    }

    fputs("} QJSXRomAtoms;\n\n", out);

    // the tables
    fputs("/* the names */\n", out);
    fputs("extern const QJSXRomAtoms qjsx_rom_atoms;\n", out);
    fputs("/* the string of each atom index, NULL for a predefined symbol (made in the\n"
          "   heap at start) */\n", out);
    fputs("extern const JSAtomStruct *const qjsx_rom_atom_ptr[QJSX_ROM_ATOM_COUNT];\n", out);
    fputs("/* open addressing by hash & (QJSX_ROM_ATOM_HASH_SIZE - 1): atom index, 0 =\n"
          "   empty slot */\n", out);
    fputs("extern const uint16_t qjsx_rom_atom_hash[QJSX_ROM_ATOM_HASH_SIZE];\n\n", out);
    fputs("#endif\n", out);
    fclose(out);
}

/**
 * Writes rom-atoms.c: the block of names (immortal reference counts, the
 * atom index in hash_next), the string of each index and the hash table.
 */
static void writeSource(const char *folder, const uint16_t *hashTable, uint32_t hashSize) {
    // the file, its header, the layout check
    FILE *out = openOutput(folder, "rom-atoms.c");
    fputs(FILE_HEADER, out);
    fputs("\n#include \"quickjs-internal.h\"\n\n#if QJSX_ROM_ATOMS\n\n", out);
    fputs("/* the layout of a name: the characters follow the JSString, as in a\n"
          "   string allocated by QuickJS */\n", out);
    fputs("_Static_assert(offsetof(JSString, u) == sizeof(JSString), \"characters after JSString\");\n\n", out);

    // the block of names
    fputs("const QJSXRomAtoms qjsx_rom_atoms = {\n", out);

    for (int i = 1; i < nameCount; i++) {
        const Name *name = &names[i];
        if (name->isSymbol) {
            continue;
        }

        fprintf(out, "    .a%d = { .header = { .ref_count = JS_REF_COUNT_IMMORTAL }, .string = { .len = %u, "
            ".hash = 0x%08x, .atom_type = JS_ATOM_TYPE_STRING, .hash_next = %d }, .text = ",
            i, name->length, name->hash, i);
        writeLiteral(out, name->text, name->length);
        fputs(" },\n", out);
    }

    fputs("};\n\n", out);

    // the string of each index
    fputs("const JSAtomStruct *const qjsx_rom_atom_ptr[QJSX_ROM_ATOM_COUNT] = {\n", out);

    for (int i = 1; i < nameCount; i++) {
        if (!names[i].isSymbol) {
            fprintf(out, "    [%d] = &qjsx_rom_atoms.a%d.string,\n", i, i);
        }
    }

    fputs("};\n\n", out);

    // the hash table, 16 slots per line
    fputs("const uint16_t qjsx_rom_atom_hash[QJSX_ROM_ATOM_HASH_SIZE] = {\n", out);

    for (uint32_t slot = 0; slot < hashSize; slot++) {
        const char *before = slot % 16 == 0 ? "    " : " ";
        const char *after = slot % 16 == 15 ? "\n" : "";
        fprintf(out, "%s%u,%s", before, hashTable[slot], after);
    }

    fputs("};\n\n#endif\n", out);
    fclose(out);
}

// ### Main ####################################################################

/**
 * Makes a runtime and a full context as qjsx does (JS_NewContext), collects
 * its names, builds the hash table (twice as many slots as names at least,
 * linear probing) and writes the two files.
 */
int main(int argc, char **argv) {
    // one argument: the output folder
    if (argc != 2) {
        fprintf(stderr, "usage: generate <output folder>\n");
        return 1;
    }

    // the names of a new context
    JSRuntime *rt = JS_NewRuntime();
    JSContext *ctx = JS_NewContext(rt);
    collectNames(rt);

    // the hash table of the string names
    uint32_t hashSize = 1;

    while (hashSize < 2 * (uint32_t)nameCount) {
        hashSize *= 2;
    }

    // each string name in the first free slot from its hash (linear probing)
    uint16_t *hashTable = calloc(hashSize, sizeof(uint16_t));

    for (int i = 1; i < nameCount; i++) {
        if (names[i].isSymbol) {
            continue;
        }

        uint32_t slot = names[i].hash & (hashSize - 1);

        while (hashTable[slot] != 0) {
            slot = (slot + 1) & (hashSize - 1);
        }

        hashTable[slot] = (uint16_t)i;
    }

    // the two files
    writeHeader(argv[1], hashSize);
    writeSource(argv[1], hashTable, hashSize);
    printf("generate: %d names (%d predefined), hash table of %u slots\n", nameCount - 1, JS_ATOM_END - 1, hashSize);

    // done
    free(hashTable);
    JS_FreeContext(ctx);
    JS_FreeRuntime(rt);
    return 0;
}
