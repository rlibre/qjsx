-- Embeds the TypeScript declarations of the JS API in the qjsx executable, as
-- the embedded module "qjsx:types". Each module has its .d.ts next to its
-- source (common/device/gpio_module.d.ts next to gpio_module.cpp,
-- lib/stdlib/src/path.d.ts next to path.js); the globals are
-- common/runtime/modules/globals.d.ts.
--
--   premake5 --file=tools/embed-types.lua embed-types --input=<repository> --output=types.cpp
--
-- 1. Every .d.ts of TYPING_FILES is read, in path order; its name is the
--    module it declares (declare module "sys/fs"), "globals" for the one
--    that declares none.
-- 2. They become a JS module: export const TYPINGS = [{ name, file, text }, ...]
--    ('file': its path in the repository).
-- 3. The JS module is written in a C++ file that registers it as an embedded
--    module of the runtime (rt::EmbeddedRegistration, as tools/embed-js.lua).
--
-- Used as a custom build rule by premake5.lua (qjsx:typings writes them in a
-- project). The C++ file is rewritten only when it changes.

local NAME = "qjsx:types"
local DELIMITER = "qjsx_types"   -- C++ raw string delimiter (16 characters at most)

-- Where the typings are, relative to the repository (premake5.lua lists the
-- same folders for the build rule).
TYPING_FILES = {
    "common/runtime/modules/*.d.ts",
    "common/device/*.d.ts",
    "host/modules/*.d.ts",
    "lib/stdlib/src/*.d.ts",
}

-- ### JS text #################################################################

-- 'text' as a JS string literal between double quotes.
local function jsString(text)
    local escaped = text:gsub('[\\"%c]', function(character)
        if character == "\\" then
            return "\\\\"
        elseif character == '"' then
            return '\\"'
        elseif character == "\n" then
            return "\\n"
        elseif character == "\r" then
            return "\\r"
        elseif character == "\t" then
            return "\\t"
        end
        return string.format("\\u%04x", character:byte())
    end)
    return '"' .. escaped .. '"'
end

-- The module a typing declares, or "globals" when it declares none.
local function declaredName(text, file)
    local name = text:match('\ndeclare module "([^"]+)"')
    if name ~= nil then
        return name
    end
    if path.getname(file) ~= "globals.d.ts" then
        error(file .. " declares no module (declare module \"name\" at column 0) and is not globals.d.ts")
    end
    return "globals"
end

-- The JS module: the declarations found under 'root', in path order.
local function jsModule(root)
    -- the files, sorted so that the module does not depend on the disk
    local files = {}
    for _, pattern in ipairs(TYPING_FILES) do
        for _, file in ipairs(os.matchfiles(path.join(root, pattern))) do
            table.insert(files, path.getrelative(root, file))
        end
    end
    table.sort(files)
    if #files == 0 then
        error("no .d.ts file under " .. root)
    end

    -- one entry per file; two files must not declare the same module
    local lines = {
        "// Generated by tools/embed-types.lua: do not edit.",
        "export const TYPINGS = [",
    }
    local seen = {}
    for _, file in ipairs(files) do
        local text = io.readfile(path.join(root, file))
        local name = declaredName(text, file)
        if seen[name] ~= nil then
            error(file .. " and " .. seen[name] .. " both declare " .. name)
        end
        seen[name] = file
        table.insert(lines, "    { name: " .. jsString(name) .. ", file: " .. jsString(file)
            .. ", text: " .. jsString(text) .. " },")
    end
    table.insert(lines, "];")
    table.insert(lines, "")
    return table.concat(lines, "\n")
end

-- ### C++ #####################################################################

-- Steps 1 to 3 (see the top of the file).
local function embedTypes(folder, output)
    -- the JS module, in a C++ raw string
    local source = jsModule(folder)
    if source:find(")" .. DELIMITER .. '"', 1, true) then
        error("a typing contains the raw string delimiter " .. DELIMITER)
    end
    local content = table.concat({
        "// Generated by tools/embed-types.lua: do not edit.",
        '#include "modules/modules.h"',
        "",
        "static const char source[] = R\"" .. DELIMITER .. "(" .. source .. ")" .. DELIMITER .. "\";",
        "",
        'static rt::EmbeddedRegistration registration("' .. NAME .. '", source);',
        "",
    }, "\n")

    -- rewrite only on change, so that make does not rebuild for nothing
    os.mkdir(path.getdirectory(output))
    if io.readfile(output) ~= content then
        io.writefile(output, content)
    end
end

newoption { trigger = "input", value = "FOLDER", description = "root of the repository" }
newoption { trigger = "output", value = "FILE", description = "C++ file to write" }

newaction {
    trigger = "embed-types",
    description = "Embed the TypeScript declarations of the JS API as the module qjsx:types",
    execute = function()
        embedTypes(_OPTIONS["input"], _OPTIONS["output"])
    end,
}
